#!/usr/bin/env python3
"""Package only public sources/dependencies; individual credentials stay on server."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import tarfile
import zipfile
ROOT=Path(__file__).resolve().parents[1]
VERSION='3.3.0-preview'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile', help='Private common-profile.json generated by the server; omit for a public Windows template')
    parser.add_argument('--output-dir', type=Path, default=ROOT/'dist', help='Release output directory (default: dist)')
    args=parser.parse_args()
    source_directories=('client/windows','client/launcher','vendor/easytier','vendor/linux-amd64/licenses','build','scripts','tests','docs')
    output=args.output_dir.expanduser().resolve()
    for directory in source_directories:
        source=(ROOT/directory).resolve()
        if output==source or source in output.parents:
            parser.error('--output-dir must be outside packaged source directories')
    for directory,names in [('vendor/easytier/linux-x86_64',['easytier-core','easytier-cli']),
            ('vendor/easytier/windows-x86_64',['easytier-core.exe','easytier-cli.exe','wintun.dll','WinDivert64.sys']),
            ('vendor/linux-amd64',['wg'])]:
        folder=ROOT/directory;manifest=json.loads((folder/'checksums.json').read_text())
        for name in names:
            if hashlib.sha256((folder/name).read_bytes()).hexdigest()!=manifest[name]:
                raise SystemExit('Dependency checksum mismatch: '+name)
    if not (ROOT/'client/windows/Civ6Relay.exe').is_file():
        raise SystemExit('Windows launcher missing; run scripts/build-launcher.py first')
    output.mkdir(parents=True,exist_ok=True)
    if output==(ROOT/'dist').resolve():
        retired=ROOT/'.build/retired-process-relay'
        for path in output.glob('*2.1.0*'):
            retired.mkdir(parents=True,exist_ok=True);shutil.move(str(path),str(retired/path.name))
    files=[ROOT/x for x in ('relayctl.py','install.sh','README.md')]
    for directory in source_directories:
        files.extend(p for p in (ROOT/directory).rglob('*') if p.is_file() and '__pycache__' not in p.parts and p.suffix!='.pyc')
    files.extend(ROOT/'vendor/linux-amd64'/x for x in ('wg','checksums.json'))
    files.append(ROOT/'vendor/sources/wireguard-tools.tar.xz')
    for path in files:
        if path.name.lower()=='packet.dll':
            raise SystemExit('Unsupported bundled dependency: Packet.dll')
        if path.is_symlink() or path.name in ('profile.json','common-profile.json','state.json','credentials.json','preferences.json',
                'identity.json','managed.json','trusted-server.json','network.toml') or path.suffix in ('.key','.psk','.conf'):
            raise SystemExit('Unexpected private/generated file: '+str(path))
    server=output/('civ6-relay-server-'+VERSION+'-linux-amd64.tar.gz')
    with tarfile.open(server,'w:gz') as archive:
        for path in sorted(set(files)):
            archive.add(str(path),arcname='civ6-relay/'+str(path.relative_to(ROOT)),recursive=False)
    client=(ROOT/'.build'/('civ6-relay-client-'+VERSION+'-windows-base.zip') if args.profile else
        output/('civ6-relay-client-'+VERSION+'-windows-template.zip'))
    client.parent.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(client,'w',zipfile.ZIP_DEFLATED) as archive:
        for directory,prefix in [('client/windows',''),('vendor/easytier/windows-x86_64','bin/'),('vendor/easytier/licenses','licenses/')]:
            folder=ROOT/directory
            for path in sorted(folder.rglob('*')):
                if path.is_file():archive.write(str(path),prefix+str(path.relative_to(folder)))
    releases=[server]
    if args.profile:
        profile=json.loads(Path(args.profile).read_text())
        if profile.get('schema')!=4 or profile.get('access_mode')!='shared' or any(k in profile for k in ('player','client_ip','instance_id','endpoint','port','network_secret')):
            raise SystemExit('Expected a common client profile without a device identity or endpoint')
        profile.update(version=VERSION,engine_version='2.6.4-civ6.2')
        common=output/('civ6-relay-client-'+VERSION+'-windows.zip')
        with common.open('wb') as f, client.open('rb') as source:
            os.chmod(str(common),0o600)
            shutil.copyfileobj(source,f,1024*1024)
        with zipfile.ZipFile(common,'a',zipfile.ZIP_DEFLATED) as archive:
            archive.writestr('profile.json',json.dumps(profile,indent=2,ensure_ascii=False)+'\n')
        releases.append(common)
    else:
        releases.append(client)
    (output/'SHA256SUMS.json').write_text(json.dumps({p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in releases},indent=2)+'\n')
    for path in releases:print(str(path))
if __name__=='__main__':main()
